#!/bin/sh
# Build the phone input page (kindle/web/page.html) into voice-page.h:
# Tailwind compiles the classes the page uses into a few kilobytes of CSS,
# which goes into the page itself, and the page into a C string.
#
# voice-page.h is kept in the repository: kterm builds without Tailwind.
# Run this after changing anything in kindle/web/. The Tailwind standalone
# executable (no Node needed) is downloaded once into build/tools.
set -eu
KINDLE_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPO=$(dirname "$KINDLE_DIR")
BUILD="${KTERM_BUILD:-$REPO/build}"
VERSION=v4.3.5
case "$(uname -s)-$(uname -m)" in
    Darwin-arm64) ASSET=tailwindcss-macos-arm64 ;;
    Darwin-x86_64) ASSET=tailwindcss-macos-x64 ;;
    Linux-x86_64) ASSET=tailwindcss-linux-x64 ;;
    Linux-aarch64) ASSET=tailwindcss-linux-arm64 ;;
    *) echo "no Tailwind executable for $(uname -s) $(uname -m)" >&2; exit 1 ;;
esac
TOOL="$BUILD/tools/$ASSET-$VERSION"
if [ ! -x "$TOOL" ]; then
    mkdir -p "$BUILD/tools"
    URL=https://github.com/tailwindlabs/tailwindcss/releases/download/$VERSION
    curl -fsSL "$URL/$ASSET" -o "$TOOL.part"
    curl -fsSL "$URL/sha256sums.txt" -o "$TOOL.sums"
    WANT=$(awk -v a="$ASSET" '$2 == a || $2 == "./" a || $2 == "*" a { print $1 }' "$TOOL.sums")
    GOT=$(shasum -a 256 "$TOOL.part" 2>/dev/null || sha256sum "$TOOL.part")
    if [ -z "$WANT" ] || [ "${GOT%% *}" != "$WANT" ]; then
        echo "checksum of $ASSET does not match" >&2
        exit 1
    fi
    chmod +x "$TOOL.part"
    mv "$TOOL.part" "$TOOL"
    rm -f "$TOOL.sums"
fi
mkdir -p "$BUILD/web"
(cd "$KINDLE_DIR/web" && "$TOOL" -i input.css -o "$BUILD/web/page.css" --minify 2>/dev/null)
python3 - "$KINDLE_DIR/web/page.html" "$BUILD/web/page.css" "$REPO/voice-page.h" <<'PY'
import sys, re
page, css, out = sys.argv[1:]
html = open(page, encoding="utf-8").read()
style = open(css, encoding="utf-8").read().strip()
html = html.replace("<!-- STYLE -->", "<style>" + style + "</style>", 1)
# comments meant for the source only
html = re.sub(r"<!--.*?-->\n?", "", html, flags=re.S)
def c(line):
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"'
lines = [c(l) for l in html.split("\n")[:-1]] if html.endswith("\n") else [c(l) for l in html.split("\n")]
with open(out, "w", encoding="utf-8") as f:
    f.write("/* voice-page.h: the phone input page, see voice.c.\n"
            " * Generated by kindle/build-web.sh from kindle/web/; do not edit. */\n\n"
            "#ifndef voice_page_h\n#define voice_page_h\n\n"
            "// one literal, longer than C99 asks compilers to take; GCC takes it\n"
            "#pragma GCC diagnostic push\n"
            "#pragma GCC diagnostic ignored \"-Woverlength-strings\"\n"
            "static const gchar VOICE_PAGE[] =\n" + "\n".join(lines) + ";\n"
            "#pragma GCC diagnostic pop\n\n#endif /* voice_page_h */\n")
print("page %d bytes, css %d bytes" % (len(html.encode()), len(style.encode())))
PY
